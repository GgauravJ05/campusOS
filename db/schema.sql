CREATE INDEX idx_notifications_user_unread ON notifications(user_id, created_at DESC)
    WHERE is_read = FALSE;

-- Backs the reminder worker's "what is due now" sweep.
CREATE INDEX idx_event_reminders_due       ON event_reminders(scheduled_for)
    WHERE dispatched_at IS NULL;

