-- ============================================================
-- 3. USERS  (FR1, FR2, FR5)
-- password_hash is nullable because Gmail OAuth accounts have no
-- local password; chk_users_credential guarantees every row still has
-- exactly one usable way to authenticate.
-- ============================================================

CREATE TABLE users (
    user_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(120) NOT NULL,
    email             VARCHAR(254) NOT NULL UNIQUE,
    password_hash     VARCHAR(255),
    oauth_provider    VARCHAR(32),
    oauth_subject     VARCHAR(255),
    phone             VARCHAR(20),
    department_id     INTEGER,
    academic_year     SMALLINT,
    profile_image_url TEXT,
    role_id           INTEGER      NOT NULL,
    is_verified       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at     TIMESTAMPTZ,
    -- Brute-force lockout (NFR: login protection). Reset on success.
    failed_login_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until      TIMESTAMPTZ,
    -- Shown on the security page. Ending old sessions on a change is done by
    -- revoking refresh_tokens, which access tokens are checked against.
    password_changed_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES roles(role_id),

    CONSTRAINT fk_users_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id),

    -- A user authenticates by password, or by OAuth, or both - never neither.
    CONSTRAINT chk_users_credential CHECK (
        password_hash IS NOT NULL OR oauth_provider IS NOT NULL
    ),

    -- OAuth identity is all-or-nothing.
    CONSTRAINT chk_users_oauth_pair CHECK (
        (oauth_provider IS NULL AND oauth_subject IS NULL)
        OR (oauth_provider IS NOT NULL AND oauth_subject IS NOT NULL)
    ),

    CONSTRAINT chk_users_academic_year CHECK (
        academic_year IS NULL OR academic_year BETWEEN 1 AND 5
    ),

    CONSTRAINT chk_users_email_shape CHECK (email = lower(email) AND email LIKE '%@%'),

    CONSTRAINT chk_users_failed_logins CHECK (failed_login_attempts >= 0)
);

CREATE UNIQUE INDEX uq_users_oauth_identity
    ON users(oauth_provider, oauth_subject)
    WHERE oauth_provider IS NOT NULL;

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ============================================================
-- 4. REFRESH TOKENS  (FR4 - session management)
-- Only the SHA-256 hash of the token is stored, so a database leak
-- does not hand an attacker usable sessions.
--
-- Tokens rotate on every refresh. All tokens descended from one sign-in
-- share a family_id; presenting an already-rotated token means it was
-- stolen and replayed, so the whole family is revoked.
-- ============================================================

CREATE TABLE refresh_tokens (
    token_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER      NOT NULL,
    family_id    UUID         NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL UNIQUE,
    user_agent   VARCHAR(255),
    ip_address   INET,
    expires_at   TIMESTAMPTZ  NOT NULL,
    revoked_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);


-- ============================================================
-- 5. OTPs
-- otp_hash stores an HMAC-SHA256 keyed with a server secret, never the
-- six plaintext digits: a plain hash of a 6-digit code is reversible in
-- a millisecond by trying all one million values.
-- ============================================================

CREATE TABLE otps (
    otp_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(254) NOT NULL,
    otp_hash     VARCHAR(64)  NOT NULL,
    purpose      VARCHAR(32)  NOT NULL DEFAULT 'EMAIL_VERIFICATION',
    attempts     SMALLINT     NOT NULL DEFAULT 0,
    expires_at   TIMESTAMPTZ  NOT NULL,
    consumed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_otps_purpose CHECK (
        purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')
    ),
    CONSTRAINT chk_otps_attempts CHECK (attempts >= 0 AND attempts <= 10)
);


