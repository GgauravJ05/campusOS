    booked_seats     INTEGER      NOT NULL DEFAULT 0,
    eligible_departments INTEGER[] NOT NULL DEFAULT '{}',  -- empty = open to all
    eligible_years   SMALLINT[]   NOT NULL DEFAULT '{}',   -- empty = open to all
