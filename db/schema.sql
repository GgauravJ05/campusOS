-- ============================================================
-- CampusOS - Smart Campus Management Platform
-- Database Schema (PostgreSQL 15+)
--
-- Apply order:
--   psql -d campusos -f db/schema.sql
--   psql -d campusos -f db/seed.sql
--
-- To rebuild from scratch (DESTRUCTIVE, dev only):
--   psql -d campusos -f db/reset.sql -f db/schema.sql -f db/seed.sql
--
-- Conventions
--   * All timestamps are TIMESTAMPTZ. The application stores UTC and
--     renders in Asia/Kolkata; never use naive TIMESTAMP here.
--   * Status columns are VARCHAR + CHECK rather than native ENUM so that
--     new states can be added without an ALTER TYPE migration.
--   * Every table that is mutated by users carries created_at/updated_at,
--     maintained by the set_updated_at() trigger.
-- ============================================================

-- ------------------------------------------------------------
-- Extensions
--   pgcrypto   -> gen_random_uuid() for certificate identifiers
--   btree_gist -> lets the bookings EXCLUDE constraint mix an equality
--                 test (venue_id) with a range overlap test (&&)
-- ------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;


-- ------------------------------------------------------------
-- Shared trigger function: keeps updated_at honest
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ============================================================
-- 1. DEPARTMENTS
-- Referenced by users, venues and coordinator routing (FR12).
-- ============================================================

CREATE TABLE departments (
    department_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code       VARCHAR(16)  NOT NULL UNIQUE,
    dept_name       VARCHAR(120) NOT NULL UNIQUE,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_departments_updated_at
    BEFORE UPDATE ON departments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ============================================================
-- 2. ROLES  (FR3 - five hierarchical roles)
-- rank_level orders the hierarchy: lower number = higher authority,
-- so "can this user act on that user" is a single integer comparison.
-- ============================================================

CREATE TABLE roles (
    role_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_key    VARCHAR(32)  NOT NULL UNIQUE,
    role_name   VARCHAR(64)  NOT NULL UNIQUE,
    rank_level  SMALLINT     NOT NULL,

    CONSTRAINT chk_roles_key CHECK (role_key IN (
        'SUPER_ADMIN',
        'DEPT_COORDINATOR',
        'CLUB_HEAD',
        'CLUB_MEMBER',
        'STUDENT'
    ))
);


-- ============================================================
-- 3. USERS  (FR1, FR2, FR5)
-- password_hash is nullable because Gmail OAuth accounts have no
-- local password; chk_users_credential guarantees every row still has
-- exactly one usable way to authenticate.
-- ============================================================

CREATE TABLE users (
    user_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(120) NOT NULL,
    email             VARCHAR(254) NOT NULL UNIQUE,
    password_hash     VARCHAR(255),
    oauth_provider    VARCHAR(32),
    oauth_subject     VARCHAR(255),
    phone             VARCHAR(20),
    department_id     INTEGER,
    academic_year     SMALLINT,
    profile_image_url TEXT,
    role_id           INTEGER      NOT NULL,
    is_verified       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES roles(role_id),

    CONSTRAINT fk_users_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id),

    -- A user authenticates by password, or by OAuth, or both - never neither.
    CONSTRAINT chk_users_credential CHECK (
        password_hash IS NOT NULL OR oauth_provider IS NOT NULL
    ),

    -- OAuth identity is all-or-nothing.
    CONSTRAINT chk_users_oauth_pair CHECK (
        (oauth_provider IS NULL AND oauth_subject IS NULL)
        OR (oauth_provider IS NOT NULL AND oauth_subject IS NOT NULL)
    ),

    CONSTRAINT chk_users_academic_year CHECK (
        academic_year IS NULL OR academic_year BETWEEN 1 AND 5
    ),

    CONSTRAINT chk_users_email_shape CHECK (email = lower(email) AND email LIKE '%@%')
);

CREATE UNIQUE INDEX uq_users_oauth_identity
    ON users(oauth_provider, oauth_subject)
    WHERE oauth_provider IS NOT NULL;

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


