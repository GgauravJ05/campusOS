-- ------------------------------------------------------------
-- 10a. EVENT ELIGIBILITY (FR15) - two junction tables, not one
--
-- events.eligible_departments INTEGER[] and eligible_years SMALLINT[] were
-- each a 1NF violation (a repeating group). They are decomposed here as TWO
-- separate junction tables rather than one combined
-- (event_id, department_id, academic_year) table - see CLAUDE.md's database
-- rules. "Eligible departments" and "eligible years" are independent facts
-- about an event: an event open to IT and CS, for years 2 and 3, means
-- "IT or CS" AND "year 2 or 3" - four combinations, not two rows. Combining
-- them into one table would force choosing a subset of that cross product
-- to store, which is a 4NF violation (a cartesian product masquerading as
-- one fact). Both composite PKs, both empty by default (empty = open to
-- everyone on that dimension, same convention the arrays used).
-- ------------------------------------------------------------

CREATE TABLE event_eligible_departments (
    event_id        INTEGER NOT NULL,
    department_id   INTEGER NOT NULL,

    PRIMARY KEY (event_id, department_id),

    CONSTRAINT fk_event_eligible_departments_event
        FOREIGN KEY (event_id) REFERENCES events(event_id) ON DELETE CASCADE,

    CONSTRAINT fk_event_eligible_departments_department
        FOREIGN KEY (department_id) REFERENCES departments(department_id) ON DELETE CASCADE
);

CREATE TABLE event_eligible_years (
    event_id        INTEGER  NOT NULL,
    academic_year   SMALLINT NOT NULL,

    PRIMARY KEY (event_id, academic_year),

    CONSTRAINT fk_event_eligible_years_event
        FOREIGN KEY (event_id) REFERENCES events(event_id) ON DELETE CASCADE,

    CONSTRAINT chk_event_eligible_years_range CHECK (academic_year BETWEEN 1 AND 5)
);


-- ============================================================
-- 11. BOOKINGS  (FR7-FR13)
--
-- start_at / end_at are the authoritative venue reservation window and
-- are the ONLY columns the conflict engine reads. They are derived by
-- the application from the event schedule at request time; events keeps
-- event_date/start_time/end_time for display and reporting.
--
-- The EXCLUDE constraint is the last line of defence: even if the
-- application-level SELECT ... FOR UPDATE logic (FR10) were buggy,
-- PostgreSQL itself refuses two overlapping APPROVED bookings on one
-- venue. The configurable setup/teardown buffer (FR9) is applied by the
-- application query, which is why the constraint uses the raw window.
-- ============================================================

CREATE TABLE bookings (
    booking_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            INTEGER      NOT NULL,
    venue_id            INTEGER      NOT NULL,
    requested_by        INTEGER      NOT NULL,
    approved_by         INTEGER,
    start_at            TIMESTAMPTZ  NOT NULL,
    end_at              TIMESTAMPTZ  NOT NULL,
    extension_minutes   SMALLINT     NOT NULL DEFAULT 0,
    -- Setup/teardown buffer (FR9) in force when the request was made. Frozen
    -- per booking so a later settings change cannot retroactively create
    -- conflicts between already-approved bookings.
    buffer_minutes      SMALLINT     NOT NULL DEFAULT 0,
    -- TRUE when faculty booked directly, skipping the pending step (FR12).
    is_direct           BOOLEAN      NOT NULL DEFAULT FALSE,
    status              VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    rejection_reason    TEXT,
    -- FR13 "Request Modification": what the approver asked the club to change.
    -- Kept after the club resubmits so the approver can see what they asked for.
    modification_note   TEXT,
    -- How many times the requester has edited and resubmitted this request.
    revision            SMALLINT     NOT NULL DEFAULT 0,
    decided_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_bookings_event
        FOREIGN KEY (event_id) REFERENCES events(event_id) ON DELETE CASCADE,

    CONSTRAINT fk_bookings_venue
        FOREIGN KEY (venue_id) REFERENCES venues(venue_id),

    CONSTRAINT fk_bookings_requested_by
        FOREIGN KEY (requested_by) REFERENCES users(user_id),

    CONSTRAINT fk_bookings_approved_by
        FOREIGN KEY (approved_by) REFERENCES users(user_id),

    CONSTRAINT chk_bookings_status CHECK (status IN (
        'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'MODIFICATION_REQUESTED'
    )),

    CONSTRAINT chk_bookings_window CHECK (end_at > start_at),

    CONSTRAINT chk_bookings_extension CHECK (
        extension_minutes >= 0 AND extension_minutes <= 15
    ),

    CONSTRAINT chk_bookings_buffer CHECK (buffer_minutes >= 0 AND buffer_minutes <= 120),

    -- FR13: a rejection must carry a recorded reason.
    CONSTRAINT chk_bookings_rejection_reason CHECK (
        status <> 'REJECTED' OR (rejection_reason IS NOT NULL AND length(btrim(rejection_reason)) > 0)
    ),

    -- FR13: sending a request back must say what to change.
    CONSTRAINT chk_bookings_modification_note CHECK (
        status <> 'MODIFICATION_REQUESTED' OR (modification_note IS NOT NULL AND length(btrim(modification_note)) > 0)
    ),

    CONSTRAINT chk_bookings_revision CHECK (revision >= 0),

    -- Any decided booking records who decided it and when.
    CONSTRAINT chk_bookings_decision_audit CHECK (
        status IN ('PENDING', 'CANCELLED')
        OR (approved_by IS NOT NULL AND decided_at IS NOT NULL)
    ),

    -- FR10: zero duplicate venue bookings, enforced by the database.
    CONSTRAINT excl_bookings_no_overlap
        EXCLUDE USING gist (
            venue_id WITH =,
            tstzrange(start_at, end_at, '[)') WITH &&
        ) WHERE (status = 'APPROVED')
);

CREATE TRIGGER trg_bookings_updated_at
    BEFORE UPDATE ON bookings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


